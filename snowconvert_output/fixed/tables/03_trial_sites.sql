CREATE OR REPLACE TABLE AZ_CLINICAL.TRIAL_SITES (
    SITE_ID         INTEGER IDENTITY(1,1),
    STUDY_ID        INTEGER NOT NULL,
    INVESTIGATOR_ID INTEGER,
    SITE_CODE       VARCHAR(20) NOT NULL,
    SITE_NAME       VARCHAR(200) NOT NULL,
    COUNTRY         VARCHAR(50) NOT NULL,
    REGION          VARCHAR(50) NOT NULL,
    ADDRESS         VARCHAR(16777216),
    ACTIVATION_DATE DATE,
    STATUS          VARCHAR(20) NOT NULL DEFAULT 'Initiating',
    CONTACT_EMAILS  ARRAY,
    NOTES           VARCHAR(255),
    CREATED_AT      TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT      TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CREATED_BY      VARCHAR(50) NOT NULL DEFAULT 'system',
    UPDATED_BY      VARCHAR(50) NOT NULL DEFAULT 'system',
    PRIMARY KEY (SITE_ID),
    UNIQUE (SITE_CODE),
    CONSTRAINT CHK_TRIAL_SITES_STATUS CHECK (STATUS IN ('Initiating','Active','Inactive','Closed'))
);
