CREATE OR REPLACE TABLE AZ_CLINICAL.STUDIES (
    STUDY_ID         INTEGER IDENTITY(1,1),
    STUDY_CODE       VARCHAR(20) NOT NULL,
    STUDY_NAME       VARCHAR(200) NOT NULL,
    PROTOCOL_NUMBER  VARCHAR(50) NOT NULL,
    PROTOCOL_VERSION VARCHAR(20) NOT NULL,
    PHASE            VARCHAR(20) NOT NULL,
    INDICATION       VARCHAR(100) NOT NULL,
    SPONSOR          VARCHAR(100) NOT NULL,
    PLANNED_SITES    INTEGER NOT NULL,
    PLANNED_SUBJECTS INTEGER NOT NULL,
    START_DATE       DATE,
    END_DATE         DATE,
    STATUS           VARCHAR(20) NOT NULL DEFAULT 'Planning',
    METADATA         VARIANT,
    CREATED_AT       TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT       TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CREATED_BY       VARCHAR(50) NOT NULL DEFAULT 'system',
    UPDATED_BY       VARCHAR(50) NOT NULL DEFAULT 'system',
    PRIMARY KEY (STUDY_ID),
    UNIQUE (STUDY_CODE),
    UNIQUE (PROTOCOL_NUMBER),
    CONSTRAINT CHK_STUDIES_PHASE  CHECK (PHASE  IN ('Phase I','Phase II','Phase III','Phase IV')),
    CONSTRAINT CHK_STUDIES_STATUS CHECK (STATUS IN ('Planning','Active','Completed','Suspended','Terminated'))
);
-- Removed: DISTSTYLE ALL / SORTKEY (STUDY_ID)  (Snowflake manages micro-partitions automatically).
