-- FIXED (RS007) - plpgsql cursor FOR..LOOP + RECORD rewritten as a single set-based INSERT ... SELECT.
-- Captured error: syntax error at 'SELECT' (FOR rec IN SELECT ... LOOP is not valid Snowflake Scripting).
-- Also: RESULT_VALUE::numeric replaced with TRY_TO_DOUBLE for safe text->number coercion.
CREATE OR REPLACE PROCEDURE AZ_CLINICAL.MONTHLY_ROLLUP()
RETURNS STRING
LANGUAGE SQL
AS
$$
BEGIN
    CREATE TABLE IF NOT EXISTS AZ_CLINICAL.MONTHLY_LAB_ROLLUP (
        SITE_ID INTEGER, SITE_CODE VARCHAR(20), MONTH DATE, TEST_CODE VARCHAR(20),
        RESULT_COUNT INTEGER, MIN_VALUE NUMBER(38,4), MAX_VALUE NUMBER(38,4), AVG_VALUE NUMBER(38,4),
        ROLLED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
    );
    TRUNCATE TABLE AZ_CLINICAL.MONTHLY_LAB_ROLLUP;
    INSERT INTO AZ_CLINICAL.MONTHLY_LAB_ROLLUP (SITE_ID, SITE_CODE, MONTH, TEST_CODE, RESULT_COUNT, MIN_VALUE, MAX_VALUE, AVG_VALUE, ROLLED_AT)
    SELECT
        s.SITE_ID, s.SITE_CODE,
        DATE_TRUNC('month', lr.COLLECTED_AT)::date AS MONTH,
        lr.TEST_CODE,
        COUNT(*),
        MIN(TRY_TO_DOUBLE(lr.RESULT_VALUE)),
        MAX(TRY_TO_DOUBLE(lr.RESULT_VALUE)),
        AVG(TRY_TO_DOUBLE(lr.RESULT_VALUE)),
        CURRENT_TIMESTAMP()
    FROM AZ_CLINICAL.LAB_RESULTS lr
    JOIN AZ_CLINICAL.PATIENTS p    ON lr.PATIENT_ID = p.PATIENT_ID
    JOIN AZ_CLINICAL.TRIAL_SITES s ON p.SITE_ID = s.SITE_ID
    WHERE lr.RESULT_STATUS = 'Final'
    GROUP BY s.SITE_ID, s.SITE_CODE, DATE_TRUNC('month', lr.COLLECTED_AT)::date, lr.TEST_CODE;
    RETURN 'OK';
END;
$$;
