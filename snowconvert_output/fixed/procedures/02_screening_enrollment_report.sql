-- Captured error: syntax error at '(' (COUNT(*) FILTER (WHERE ...)); RECORD / RAISE NOTICE also invalid.
-- RAISE EXCEPTION guard preserved as an early RETURN when there are no screened patients.
CREATE OR REPLACE PROCEDURE AZ_CLINICAL.SCREENING_ENROLLMENT_REPORT()
RETURNS STRING
LANGUAGE SQL
AS
$$
DECLARE
    v_total_screened INTEGER;
BEGIN
    CREATE TABLE IF NOT EXISTS AZ_CLINICAL.SCREENING_ENROLLMENT_SUMMARY (
        SITE_ID INTEGER, SITE_CODE VARCHAR(20), SITE_NAME VARCHAR(200), MONTH DATE,
        SCREENED_COUNT INTEGER, ENROLLED_COUNT INTEGER, CONVERSION_RATE NUMBER(5,2),
        GENERATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
    );
    TRUNCATE TABLE AZ_CLINICAL.SCREENING_ENROLLMENT_SUMMARY;

    SELECT COUNT(*) INTO v_total_screened FROM AZ_CLINICAL.PATIENTS WHERE SCREENING_DATE IS NOT NULL;
    IF (v_total_screened = 0) THEN
        RETURN 'No screened patients found; cannot generate report.';
    END IF;

    INSERT INTO AZ_CLINICAL.SCREENING_ENROLLMENT_SUMMARY (SITE_ID, SITE_CODE, SITE_NAME, MONTH, SCREENED_COUNT, ENROLLED_COUNT, CONVERSION_RATE, GENERATED_AT)
    SELECT
        s.SITE_ID, s.SITE_CODE, s.SITE_NAME,
        DATE_TRUNC('month', p.SCREENING_DATE)::date AS MONTH,
        COUNT_IF(p.STATUS IN ('Screening','Screen Failed'))        AS SCREENED_COUNT,
        COUNT_IF(p.STATUS IN ('Active','Completed','Withdrawn'))   AS ENROLLED_COUNT,
        CASE WHEN COUNT_IF(p.STATUS IN ('Screening','Screen Failed')) = 0 THEN 0
             ELSE ROUND(COUNT_IF(p.STATUS IN ('Active','Completed','Withdrawn'))::float
                        / COUNT_IF(p.STATUS IN ('Screening','Screen Failed')) * 100, 2) END AS CONVERSION_RATE,
        CURRENT_TIMESTAMP()
    FROM AZ_CLINICAL.PATIENTS p
    JOIN AZ_CLINICAL.TRIAL_SITES s ON p.SITE_ID = s.SITE_ID
    WHERE p.SCREENING_DATE IS NOT NULL
    GROUP BY s.SITE_ID, s.SITE_CODE, s.SITE_NAME, DATE_TRUNC('month', p.SCREENING_DATE)::date;
    RETURN 'OK';
END;
$$;
